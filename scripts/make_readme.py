"""Generate the GitHub-safe terminal layout without inline HTML styles."""
import argparse
from html import escape
from pathlib import Path

try:
    from .common import ROOT, atomic_write, load_profile
except ImportError:
    from common import ROOT, atomic_write, load_profile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'README.md')
    args = parser.parse_args()
    username = escape(load_profile(args.config)['username'])
    content = f'''<!-- Generated by scripts/make_readme.py. Edit profile.json to personalize. -->
<div align="center">
  <h3><code>{username}@github ~ $ ./contributions.sh</code></h3>
  <img src="./contrib-heatmap.svg" width="860" alt="Real contribution calendar for {username}, refreshed daily" />
  <br><br>
  <h3><code>{username}@github ~ $ whoami</code></h3>
  <table>
    <tr>
      <td valign="top"><img src="./avi-ascii.svg" width="370" alt="Monochrome ASCII avatar of {username}" /></td>
      <td valign="top"><img src="./info-card.svg" width="490" alt="{username}'s Neofetch-style profile information" /></td>
    </tr>
  </table>
  <br>
  <p><sub>Characters. Contributions. A little context.</sub></p>
  <p><sub><a href="./SETUP.md">Setup &amp; customization</a> · <a href="./profile.json">Profile config</a></sub></p>
</div>
'''
    atomic_write(args.output, content)
    print(f'Wrote {args.output}')


if __name__ == '__main__':
    main()
